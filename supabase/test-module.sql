-- Isolated storage for the three experimental paper-trading strategies.
-- Run once in Supabase SQL Editor before enabling the Test tab.
create table if not exists public.test_settings (
  id integer primary key check (id = 1),
  enabled jsonb not null default '{"brooks":true,"cameron":true,"smb":true}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.test_state (
  id integer primary key check (id = 1),
  timeframe text not null default '1m',
  price numeric,
  signals jsonb not null default '{"brooks":"WAIT","cameron":"WAIT","smb":"WAIT"}'::jsonb,
  analysis jsonb,
  updated_at timestamptz not null default now()
);

alter table public.test_state add column if not exists analysis jsonb;

create table if not exists public.test_trades (
  id bigint generated by default as identity primary key,
  trade_key text not null unique,
  strategy text not null check (strategy in ('brooks','cameron','smb')),
  timeframe text not null,
  candle_time bigint not null,
  trade_time bigint not null,
  side text not null check (side in ('BUY','SELL')),
  entry numeric not null,
  sl numeric not null,
  tp numeric not null,
  exit numeric,
  pnl numeric,
  status text not null default 'OPEN' check (status in ('OPEN','CLOSED')),
  result text,
  updated_at timestamptz not null default now()
);

create index if not exists test_trades_status_idx on public.test_trades(status);
create index if not exists test_trades_strategy_time_idx on public.test_trades(strategy, trade_time desc);

alter table public.test_settings enable row level security;
alter table public.test_state enable row level security;
alter table public.test_trades enable row level security;

revoke all on public.test_settings, public.test_state, public.test_trades from anon, authenticated;
grant all on public.test_settings, public.test_state, public.test_trades to service_role;
grant usage, select on sequence public.test_trades_id_seq to service_role;

insert into public.test_settings (id) values (1) on conflict (id) do nothing;
insert into public.test_state (id) values (1) on conflict (id) do nothing;
